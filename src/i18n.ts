export function getLocalizedExchangeRateNote(note: string | undefined, lang: Language = 'zh'): string {
  if (!note) return '';
  const trimmed = note.trim().replace(/^\(|\)$/g, '').trim();

  // If the note matches Chinese standard default notes
  const isDefaultNote = 
    trimmed === '依据每周实际支付汇率及成本平均计算' ||
    trimmed === '依据每周实际支付汇率及支付成本平均计算' ||
    trimmed === '和实际支付汇率截图一致' ||
    trimmed === '与实际支付汇率截图一致' ||
    trimmed.includes('实际支付汇率');

  if (isDefaultNote) {
    return translations[lang].defaultExchangeRateNote;
  }

  return note;
}

